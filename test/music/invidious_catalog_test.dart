const _songId = 'dQw4w9WgXcQ';
const _channelId = 'UC0123456789012345678901';
const _playlistId = 'PLtest_music';

Map<String, Object?> _song({int index = 0}) => {
      'type': 'video',
      'videoId': _songId,
      'title': 'Test song',
      'author': 'Test artist',
      'authorId': _channelId,
      'lengthSeconds': 212,
      'index': index,
      'videoThumbnails': [
        {
          'url': '/vi/$_songId/mqdefault.jpg',
          'width': 320,
          'height': 180,
        }
      ],
    };

Map<String, Object?> _channel() => {
      'type': 'channel',
      'author': 'Test artist',
      'authorId': _channelId,
      'authorUrl': '/channel/$_channelId',
      'authorThumbnails': <Object>[],
      'subCount': 10,
      'autoGenerated': false,
      'description': 'Artist channel',
    };

Map<String, Object?> _playlist({List<Object>? songs, int count = 3}) => {
      'type': 'playlist',
      'playlistId': _playlistId,
      'title': 'Test playlist',
      'author': 'Test curator',
      'videoCount': count,
      'videos': songs ?? [_song()],
    };

http.Response _json(Object body, http.Request request) =>
    http.Response(jsonEncode(body), 200,
        request: request, headers: {'content-type': 'application/json'});

class _UnimplementedCatalog extends MusicCatalogService {}

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();
  late MockClient client;
  late InvidiousMusicCatalogService catalog;
  late Future<http.Response> Function(http.Request) respond;
  final requests = <http.Request>[];

  setUp(() async {
    db = await SembastSqfDb.createInMemory();
    await NetworkProxy.instance.initialize(saved: '{}', configureNative: false);
    await db.upsertServer(const Server(url: 'https://invidious.example'));
    requests.clear();
    respond = (request) async => _json([], request);
    client = MockClient((request) async {
      requests.add(request);
      return respond(request);
    });
    catalog = InvidiousMusicCatalogService(api: Service(httpClient: client));
  });

  tearDown(() async {
    client.close();
    await NetworkProxy.instance.initialize(saved: '{}', configureNative: false);
    await db.close();
  });

  test('the production catalog defaults to Invidious', () {
    expect(musicCatalogService, isA<InvidiousMusicCatalogService>());
  });

  test('unimplemented catalog methods fail without a network fallback',
      () async {
    final contract = _UnimplementedCatalog();
    for (final request in <Future<Object> Function()>[
      () => contract.searchSongs('song'),
      () => contract.searchArtists('artist'),
      () => contract.searchPlaylists('playlist'),
      contract.getTrendingSongs,
      () => contract.getSong(_songId),
      () => contract.getArtist(_channelId),
      () => contract.getPlaylist(_playlistId),
    ]) {
      await expectLater(request(), throwsA(isA<MusicCatalogUnsupported>()));
    }
    expect(requests, isEmpty);
  });

  for (final origin in [
    'https://invidious.nerdvpn.de',
    'https://invidious.dvbeckwitt.duckdns.org',
  ]) {
    test('catalog requests retain $origin and its account context', () async {
      final account = Server(url: origin, id: 'music-account', customHeaders: {
        'X-Instance-Access': 'fixture-access',
      });
      await db.upsertServer(account);
      await db.useServer(account);
      respond = (request) async {
        expect(request.url.origin, origin);
        expect(request.headers['X-Instance-Access'], 'fixture-access');
        expect(
            GatewayRequestContext.tryParse(
                    request.headers[gatewayContextHeader]!)!
                .key,
            GatewayRequestContext.forAccount(
                    account.profileId, account.accountId, origin)!
                .key);
        switch (request.url.path) {
          case '/api/v1/search':
            return _json(
                switch (request.url.queryParameters['type']) {
                  'channel' => [_channel()],
                  'playlist' => [_playlist()],
                  _ => [_song()],
                },
                request);
          case '/api/v1/trending':
            expect(request.url.queryParameters['type'], 'Music');
            return _json([_song()], request);
          case '/api/v1/videos/$_songId':
            return _json(_song(), request);
          case '/api/v1/channels/$_channelId':
            return _json(_channel(), request);
          case '/api/v1/channels/$_channelId/videos':
            expect(request.url.queryParameters['sort_by'], 'popular');
            return _json({
              'videos': [_song()]
            }, request);
          case '/api/v1/playlists/$_playlistId':
            final page = int.parse(request.url.queryParameters['page']!);
            return _json(
                _playlist(songs: [
                  if (page == 1) _song(index: 0),
                  _song(index: page),
                ]),
                request);
          default:
            fail('Unexpected catalog endpoint: ${request.url.path}');
        }
      };

      final songs = await catalog.searchSongs('Test song');
      expect(songs.single.artists, ['Test artist']);
      expect(songs.single.artistLinks.single.id, _channelId);
      expect(await catalog.searchArtists('Test artist'), hasLength(1));
      expect(await catalog.searchPlaylists('Test playlist'), hasLength(1));
      expect(await catalog.getTrendingSongs(), hasLength(1));
      expect((await catalog.getSong(_songId)).videoId, _songId);
      expect((await catalog.getArtist(_channelId)).songs, hasLength(1));
      final collection = await catalog.getPlaylist('VL$_playlistId');
      // Repeated recordings are distinct playlist occurrences.
      expect(collection.tracks.map((track) => track.videoId),
          [_songId, _songId, _songId]);
      expect(requests, hasLength(9));
      expect(requests.every((request) => request.url.origin == origin), isTrue);
    });
  }

  test('exclusive catalog identities cannot enter supported endpoints', () {
    for (final call in <Future<Object> Function()>[
      () => catalog.getSong('MPREalbum'),
      () => catalog.getArtist('FEmusic_charts'),
      () => catalog.getPlaylist('MPREalbum'),
      () => catalog.getPlaylist('FEmusic_new_releases_albums'),
      () => catalog.getPlaylist('FEmusic_moods_and_genres'),
    ]) {
      expect(call, throwsA(isA<MusicCatalogException>()));
    }
    expect(requests, isEmpty);
  });

  test('saved RD mixes use the standard mixes endpoint without pagination',
      () async {
    const mixId = 'RD$_songId';
    respond = (request) async {
      expect(request.url.path, '/api/v1/mixes/$mixId');
      expect(request.url.queryParameters, isNot(contains('page')));
      return _json({
        'mixId': mixId,
        'title': 'Test mix',
        'videos': [
          {..._song(index: 0), 'title': 'First occurrence'},
          {..._song(index: 1), 'title': 'Second occurrence'},
        ],
      }, request);
    };
    final collection = await catalog.getPlaylist(mixId);
    expect(collection.title, 'Test mix');
    expect(collection.tracks.map((track) => track.title),
        ['First occurrence', 'Second occurrence']);
    expect(requests, hasLength(1));
  });

  test('mismatched mix metadata is rejected', () async {
    respond = (request) async => _json({
          'mixId': 'RDother_mix',
          'title': 'Wrong mix',
          'videos': [_song()],
        }, request);
    await expectLater(catalog.getPlaylist('RD$_songId'),
        throwsA(isA<InvidiousServiceError>()));
    expect(requests, hasLength(1));
  });

  test('an instance failure never retries the direct catalog', () async {
    respond = (request) async => http.Response('Unavailable', 503,
        request: request, headers: {'content-type': 'text/plain'});
    await expectLater(
        catalog.searchSongs('song'), throwsA(isA<InvidiousServiceError>()));
    expect(requests.single.url.host, 'invidious.example');
  });

  for (final interactive in [false, true]) {
    test('song lookup rejects another recording, interactive=$interactive',
        () async {
      respond = (request) async =>
          _json({..._song(), 'videoId': 'aaaaaaaaaaa'}, request);
      await expectLater(
          catalog.getSong(_songId,
              loadObserver: interactive
                  ? VideoLoadObserver(
                      isCurrent: () => true,
                      onRetry: () {
                        fail('Wrong-recording metadata must not be retried');
                      })
                  : null),
          throwsA(isA<MusicCatalogException>()));
      expect(requests, hasLength(1));
    });
  }

  test('interactive song links retry metadata through the same instance',
      () async {
    catalog = InvidiousMusicCatalogService(
        api: Service(httpClient: client, wait: (_) async {}));
    var retries = 0;
    respond = (request) async => requests.length == 1
        ? http.Response('{"error":"Temporarily unavailable"}', 503,
            request: request, headers: {'content-type': 'application/json'})
        : _json(_song(), request);
    final song = await catalog.getSong(_songId,
        loadObserver:
            VideoLoadObserver(isCurrent: () => true, onRetry: () => retries++));

    expect(song.videoId, _songId);
    expect(song.playbackVideo?.videoId, _songId);
    expect(song.playbackVideo?.formatStreams, isNotNull);
    expect(song.playbackVideo?.adaptiveFormats, isNotNull);
    expect(song.playbackVideo?.playbackConnection?.server.url,
        'https://invidious.example');
    expect(song.playbackVideo?.backendPlayback, isNull);
    expect(song.playbackVideo?.playbackSourceId, isNotNull);
    expect(song.toVideo().formatStreams, isNull);
    expect(song.toVideo().backendPlayback, isNull);
    expect(song.toVideo().playbackConnection, isNull);
    expect(song.toVideo().playbackSourceId, isNull);
    expect(retries, 1);
    expect(requests, hasLength(2));
    expect(requests.last.url, requests.first.url);
    expect(requests.last.headers, requests.first.headers);
    expect(requests.last.url.host, 'invidious.example');
    expect(requests.last.url.queryParameters['local'], 'true');
  });

  test('leaving an interactive song link stops its scheduled metadata retry',
      () async {
    var current = true;
    catalog = InvidiousMusicCatalogService(
        api: Service(
            httpClient: client,
            wait: (_) async {
              current = false;
            }));
    respond = (request) async => http.Response(
        '{"error":"Temporarily unavailable"}', 503,
        request: request, headers: {'content-type': 'application/json'});

    await expectLater(
        catalog.getSong(_songId,
            loadObserver:
                VideoLoadObserver(isCurrent: () => current, onRetry: () {})),
        throwsA(isA<StateError>()));
    expect(requests, hasLength(1));
  });

  test('song links retain the recovered backend for immediate playback',
      () async {
    final selector = BackendSelector('ROUTE',
        const [BackendOption('first', 'First'), BackendOption('next', 'Next')],
        automaticFallback: true);
    final selected =
        selector.withSelection(await db.getCurrentlySelectedServer(), 'first');
    await db.upsertServer(selected);
    catalog = InvidiousMusicCatalogService(
        api: Service(httpClient: client, wait: (_) async {}));
    respond = (request) async => request.headers['Cookie'] == 'ROUTE=first'
        ? http.Response('{"error":"Temporarily unavailable"}', 503,
            request: request, headers: {'content-type': 'application/json'})
        : _json(_song(), request);

    final song = await catalog.getSong(_songId,
        loadObserver: VideoLoadObserver(isCurrent: () => true, onRetry: () {}));
    final playback = song.playbackVideo!.backendPlayback!;
    expect(requests, hasLength(3));
    expect(playback.server.backendSelector!.selectedValue(playback.server),
        'next');
    expect(playback.retries, 1);
    expect(playback.matches(await db.getCurrentlySelectedServer()), isTrue);
    expect(song.toVideo().backendPlayback, isNull);
  });

  test('noninteractive song lookups do not add the interactive retry',
      () async {
    respond = (request) async => http.Response(
        '{"error":"Temporarily unavailable"}', 503,
        request: request, headers: {'content-type': 'application/json'});
    await expectLater(
        catalog.getSong(_songId), throwsA(isA<InvidiousServiceError>()));
    expect(requests, hasLength(1));
  });

  test('an artist lookup rejects another channel before loading songs',
      () async {
    respond = (request) async =>
        _json({..._channel(), 'authorId': 'UCaaaaaaaaaaaaaaaaaaaaaa'}, request);
    await expectLater(
        catalog.getArtist(_channelId), throwsA(isA<MusicCatalogException>()));
    expect(requests, hasLength(1));
  });

  test('opening a Music artist preserves the channel notification cursor',
      () async {
    final documents =
        await Directory.systemTemp.createTemp('videre-music-artist-test-');
    const pathProvider = MethodChannel('plugins.flutter.io/path_provider');
    final messenger =
        TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger;
    messenger.setMockMethodCallHandler(
        pathProvider, (_) async => documents.path);
    addTearDown(() async {
      messenger.setMockMethodCallHandler(pathProvider, null);
      await documents.delete(recursive: true);
    });
    final account = await db.getCurrentlySelectedServer();
    final notificationStore = fileDb.forAccount(account);
    const channelUrl = '/channel/$_channelId';
    await notificationStore.upsertChannelNotification(
        ChannelNotification(channelUrl, 'Test artist', 'previous-video', 42));
    respond = (request) async => request.url.path.endsWith('/videos')
        ? _json({
            'videos': [_song()]
          }, request)
        : _json({
            ..._channel(),
            'latestVideos': [_song()]
          }, request);

    final api = Service(httpClient: client);
    catalog = InvidiousMusicCatalogService(api: api);
    expect((await catalog.getArtist(_channelId)).songs, hasLength(1));
    final cursor = await notificationStore.getChannelNotification(channelUrl);
    expect(cursor!.lastSeenVideoId, 'previous-video');
    expect(cursor.timestamp, 42);

    await api.getChannel(_channelId);
    expect(
        (await notificationStore.getChannelNotification(channelUrl))!
            .lastSeenVideoId,
        _songId);
  });

  test('a server switch discards search results from the previous account',
      () async {
    final pending = Completer<http.Response>();
    final started = Completer<http.Request>();
    respond = (request) {
      started.complete(request);
      return pending.future;
    };
    final search = catalog.searchSongs('song');
    final request = await started.future;
    const other = Server(url: 'https://other.example');
    await db.upsertServer(other);
    await db.useServer(other);
    pending.complete(_json([_song()], request));
    await expectLater(search, throwsA(isA<MusicCatalogException>()));
    expect(requests, hasLength(1));
  });

  test('a server switch stops playlist pagination', () async {
    respond = (request) async {
      const other = Server(url: 'https://other.example');
      await db.upsertServer(other);
      await db.useServer(other);
      return _json(_playlist(count: 100), request);
    };
    await expectLater(catalog.getPlaylist(_playlistId),
        throwsA(isA<MusicCatalogException>()));
    expect(requests, hasLength(1));
  });

  test('a backend preference change stops playlist pagination', () async {
    final selector = BackendSelector('backend', const [
      BackendOption('first', 'First'),
      BackendOption('second', 'Second'),
    ]);
    final account =
        selector.withSelection(await db.getCurrentlySelectedServer(), 'first');
    await db.upsertServer(account);
    respond = (request) async {
      expect(request.headers['Cookie'], 'backend=first');
      await db.upsertServer(selector.withSelection(account, 'second'));
      return _json(_playlist(count: 100), request);
    };
    await expectLater(catalog.getPlaylist(_playlistId),
        throwsA(isA<MusicCatalogException>()));
    expect(requests, hasLength(1));
  });

  test('a network route change stops playlist pagination', () async {
    respond = (request) async {
      await NetworkProxy.instance.initialize(
          saved: '{"enabled":true,"host":"127.0.0.1","port":19050}',
          configureNative: false);
      return _json(_playlist(count: 100), request);
    };
    await expectLater(catalog.getPlaylist(_playlistId),
        throwsA(isA<MusicCatalogException>()));
    expect(requests, hasLength(1));
  });

  test('terminal empty page completes playlists with unavailable entries',
      () async {
    respond = (request) async => _json(
        _playlist(
            songs: request.url.queryParameters['page'] == '1' ? [_song()] : [],
            count: 3),
        request);
    final collection = await catalog.getPlaylist(_playlistId);
    expect(collection.tracks.map((track) => track.videoId), [_songId]);
    expect(requests, hasLength(2));
  });

  test('overlapping Invidious pages preserve every playlist occurrence',
      () async {
    respond = (request) async {
      final page = int.parse(request.url.queryParameters['page']!);
      final start = switch (page) { 1 => 0, 2 => 50, _ => 150 };
      final end = switch (page) { 1 => 200, 2 => 250, _ => 300 };
      return _json(
          _playlist(count: 300, songs: [
            for (var index = start; index < end; index++)
              {..._song(index: index), 'title': 'Occurrence $index'},
          ]),
          request);
    };
    final collection = await catalog.getPlaylist(_playlistId);
    expect(collection.tracks.map((track) => track.title),
        [for (var index = 0; index < 300; index++) 'Occurrence $index']);
    expect(
        collection.tracks.every((track) => track.videoId == _songId), isTrue);
    expect(requests, hasLength(3));
  });

  test('filtered overlap does not prematurely finish a playlist', () async {
    respond = (request) async {
      final page = int.parse(request.url.queryParameters['page']!);
      final indices = switch (page) {
        1 => [0, 1, 2, 3, 4],
        2 => [1, 2, 3, 4, 5],
        3 => [6],
        _ => <int>[],
      };
      return _json(
          _playlist(count: 7, songs: [
            for (final index in indices)
              {
                ..._song(index: index),
                'title': index == 1 || index == 3
                    ? '[Private video]'
                    : 'Occurrence $index',
              },
          ]),
          request);
    };
    final collection = await catalog.getPlaylist(_playlistId);
    expect(collection.tracks.map((track) => track.title), [
      'Occurrence 0',
      'Occurrence 2',
      'Occurrence 4',
      'Occurrence 5',
      'Occurrence 6',
    ]);
    expect(requests, hasLength(4));
  });

  for (final omittedByServer in [false, true]) {
    test('unavailable entries allow final lookback (omitted=$omittedByServer)',
        () async {
      respond = (request) async {
        final page = int.parse(request.url.queryParameters['page']!);
        final start =
            switch (page) { 1 => 0, 2 => 50, 3 => 150, 4 => 250, _ => 300 };
        final end = switch (page) { 1 => 200, 2 => 250, _ => 300 };
        return _json(
            _playlist(count: 300, songs: [
              for (var index = start; index < end; index++)
                if (!omittedByServer || index != 10)
                  {
                    ..._song(index: index),
                    'title':
                        index == 10 ? '[Private video]' : 'Occurrence $index',
                  },
            ]),
            request);
      };
      final collection = await catalog.getPlaylist(_playlistId);
      expect(collection.tracks.map((track) => track.title), [
        for (var index = 0; index < 300; index++)
          if (index != 10) 'Occurrence $index',
      ]);
      expect(requests, hasLength(5));
    });
  }

  test('repeated playlist pages do not manufacture a complete collection',
      () async {
    respond = (request) async => _json(_playlist(count: 2), request);
    await expectLater(catalog.getPlaylist(_playlistId),
        throwsA(isA<MusicCatalogException>()));
    expect(requests, hasLength(2));
  });

  test('reordered pages with no new occurrences cannot loop', () async {
    respond = (request) async => _json(
        _playlist(count: 3, songs: [
          for (final index
              in request.url.queryParameters['page'] == '1' ? [0, 1] : [1, 0])
            _song(index: index),
        ]),
        request);
    await expectLater(catalog.getPlaylist(_playlistId),
        throwsA(isA<MusicCatalogException>()));
    expect(requests, hasLength(3));
  });

  test('playlist metadata changes do not mix different collections', () async {
    respond = (request) async => _json(
        _playlist(count: request.url.queryParameters['page'] == '1' ? 3 : 4),
        request);
    await expectLater(catalog.getPlaylist(_playlistId),
        throwsA(isA<MusicCatalogException>()));
    expect(requests, hasLength(2));
  });

  test('playlist loading has a finite page budget', () async {
    respond = (request) async => _json(
        _playlist(songs: [
          _song(index: int.parse(request.url.queryParameters['page']!))
        ], count: 51),
        request);
    await expectLater(catalog.getPlaylist(_playlistId),
        throwsA(isA<MusicCatalogException>()));
    expect(requests, hasLength(50));
  });

  test('blank queries and invalid identifiers do not request data', () async {
    expect(await catalog.searchSongs('  '), isEmpty);
    expect(await catalog.searchArtists(''), isEmpty);
    expect(await catalog.searchPlaylists('\n'), isEmpty);
    expect(() => catalog.getSong('../video'),
        throwsA(isA<MusicCatalogException>()));
    expect(() => catalog.getArtist('../channel'),
        throwsA(isA<MusicCatalogException>()));
    expect(() => catalog.getPlaylist('../playlist'),
        throwsA(isA<MusicCatalogException>()));
    expect(requests, isEmpty);
  });
}
