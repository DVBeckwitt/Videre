const _songId = 'dQw4w9WgXcQ';
const _channelId = 'UC0123456789012345678901';
const _playlistId = 'PLtest_music';

Map<String, Object?> _song({int index = 0}) => {
      'type': 'video',
      'videoId': _songId,
      'title': 'Test song',
      'author': 'Test artist',
      'authorId': _channelId,
      'lengthSeconds': 212,
      'index': index,
      'videoThumbnails': [
        {
          'url': '/vi/$_songId/mqdefault.jpg',
          'width': 320,
          'height': 180,
        }
      ],
    };

String _discoveryId(int index) => index.toString().padLeft(11, 'v');

Map<String, Object?> _discoveryVideo(int index, {String? genre = 'Music'}) => {
      ..._song(),
      'videoId': _discoveryId(index),
      'title': 'Discovered song $index',
      'genre': genre,
    };

Map<String, Object?> _channel() => {
      'type': 'channel',
      'author': 'Test artist',
      'authorId': _channelId,
      'authorUrl': '/channel/$_channelId',
      'authorThumbnails': <Object>[],
      'subCount': 10,
      'autoGenerated': false,
      'description': 'Artist channel',
    };

Map<String, Object?> _playlist({List<Object>? songs, int count = 3}) => {
      'type': 'playlist',
      'playlistId': _playlistId,
      'title': 'Test playlist',
      'author': 'Test curator',
      'videoCount': count,
      'videos': songs ?? [_song()],
    };

http.Response _json(Object body, http.Request request) =>
    http.Response(jsonEncode(body), 200,
        request: request, headers: {'content-type': 'application/json'});

