  'videoId': videoId,
  'type': 'video',
  'title': 'Song',
  'author': 'Artist',
  'index': 0
};
const privateSong = {
  'videoId': 'hidden12345',
  'type': 'video',
  'title': '[Private video]',
  'index': 1
};
const channel = {
  'type': 'channel',
  'authorId': channelId,
  'author': 'Artist',
  'authorUrl': '/channel/$channelId',
  'authorThumbnails': [],
  'subCount': 10,
  'autoGenerated': false,
  'description': 'Description',
  'latestVideos': [song],
