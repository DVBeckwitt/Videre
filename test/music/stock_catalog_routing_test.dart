import 'package:http/http.dart' as http;
import 'package:http/testing.dart';

const instance = 'https://invidious.example';
const videoId = 'abcdefghijk';
const channelId = 'UC0123456789012345678901';
const playlistId = 'PLstockmusic';
const mixId = 'RDabcdefghijk';
const song = {
  'videoId': videoId,
  'type': 'video',
  'title': 'Song',
  'author': 'Artist',
  'index': 0
};
const privateSong = {
  'videoId': 'hidden12345',
  'type': 'video',
  'title': '[Private video]',
  'index': 1
};
const channel = {
  'type': 'channel',
  'authorId': channelId,
  'author': 'Artist',
  'authorUrl': '/channel/$channelId',
  'authorThumbnails': [],
  'subCount': 10,
  'autoGenerated': false,
  'description': 'Description',
  'latestVideos': [song],
};
const playlist = {
  'type': 'playlist',
  'playlistId': playlistId,
  'title': 'Playlist',
  'author': 'Artist',
  'videoCount': 2,
  'videos': [song, privateSong]
};

http.Response json(http.Request request, Object value, {int status = 200}) =>
    http.Response(jsonEncode(value), status,
        request: request, headers: {'content-type': 'application/json'});

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();
  final calls = <Uri>[];
  late Service api;
  late Service previous;
  late Future<http.Response> Function(http.Request) respond;
  late Future<void> Function(Duration) waitForRetry;

  setUp(() async {
    db = await SembastSqfDb.createInMemory();
    await NetworkProxy.instance.initialize(saved: '{}', configureNative: false);
    await db.upsertServer(const Server(url: instance));
    await db.saveSetting(SettingsValue(dearrowSettingName, 'true'));
    await db.saveSetting(SettingsValue(dearrowThumbnailsSettingName, 'true'));
    calls.clear();
    waitForRetry = (_) async {};
    previous = service;
    api = service = Service(
        wait: (delay) => waitForRetry(delay),
        httpClient: MockClient((request) async {
          calls.add(request.url);
          return respond(request);
        }));
    respond = (request) async {
      if (request.url.origin != instance) {
        return json(request, {'titles': [], 'thumbnails': []});
      }
      switch (request.url.path) {
        case '/api/v1/search':
          // Even a mixed instance response on a channel or playlist search
          // must not send its incidental video IDs to a third party.
          return json(request, [song, privateSong, channel, playlist]);
        case '/api/v1/videos/$videoId':
          return json(request, {
            ...song,
            'recommendedVideos': [song, privateSong]
          });
        case '/api/v1/channels/$channelId':
          return json(request, channel);
        case '/api/v1/channels/$channelId/videos':
          return json(request, {
            'videos': [song, privateSong]
          });
        case '/api/v1/playlists/$playlistId':
          return json(request, {
            ...playlist,
            if (request.url.queryParameters['page'] != '1') 'videos': []
          });
        case '/api/v1/mixes/$mixId':
          return json(request, {
            'mixId': mixId,
            'title': 'Mix',
            'videos': [song, privateSong]
          });
        default:
          fail('Unexpected instance path ${request.url.path}');
      }
    };
  });
  tearDown(() async {
    service = previous;
    api.httpClient.close();
    await NetworkProxy.instance.initialize(saved: '{}', configureNative: false);
    await db.close();
  });

  test(
      'Music search, song, channel, playlist and mix keep original filtered instance results',
      () async {
    final music = InvidiousMusicCatalogService(api: api);
    expect((await music.searchSongs('Song')).single.title, 'Song');
    expect((await music.searchArtists('Artist')).single.id, channelId);
    expect((await music.searchPlaylists('Playlist')).single.id, playlistId);
    expect((await music.getSong(videoId)).title, 'Song');
    expect((await music.getArtist(channelId)).songs.single.videoId, videoId);
    expect(
        (await music.getPlaylist(playlistId)).tracks.single.videoId, videoId);
    expect((await music.getPlaylist(mixId)).tracks.single.videoId, videoId);
    expect(calls, isNotEmpty);
    expect(
        calls.every((url) =>
            url.origin == instance && url.queryParameters['local'] == 'true'),
        isTrue);

    // The same preference still enriches the regular Video workflow.
    calls.clear();
    await api.getVideo(videoId);
    expect(calls.any((url) => url.host == 'sponsor.ajay.app'), isTrue);
  });

  test('manual Music backend and subsequent recovery stay on the instance',
      () async {
    final selector = BackendSelector('ROUTE',
        const [BackendOption('one', 'One'), BackendOption('two', 'Two')],
        automaticFallback: true);
    final selected = selector.withSelection(
        const Server(url: instance).copyWith(backendSelector: selector), 'one');
    await db.upsertServer(selected);
    await db.useServer(selected);
    final starting = await api.getMusicVideoForBackend(
        videoId, BackendPlayback.manual(selected, 'one'));
    expect(starting.recommendedVideos.single.title, 'Song');
    final recovered = await api.retryVideoBackend(
        starting.copyWith(
            musicMetadata:
                const MusicMetadata(title: 'Song', artist: 'Artist')),
        isCurrent: () => true);
    expect(recovered?.backendPlayback?.retryIndex, 1);
    expect(recovered?.musicMetadata?.title, 'Song');
    expect(calls.map((url) => url.origin), [instance, instance]);
  });

  final lookups = <String, Future<Object> Function(MusicCatalogService)>{
    'search': (music) => music.searchSongs('Song'),
    'discovery search': (music) => music.getDiscoverySongs(),
    'artist': (music) => music.getArtist(channelId),
    'playlist': (music) => music.getPlaylist(playlistId),
    'mix': (music) => music.getPlaylist(mixId),
    'song': (music) => music.getSong(videoId),
  };
  for (final lookup in lookups.entries) {
    for (final change in ['account', 'proxy']) {
      test(
          'Music ${lookup.key} drops a rate-limit retry after switching $change',
          () async {
        final music = InvidiousMusicCatalogService(api: api);
        waitForRetry = (_) async {
          if (change == 'account') {
            const other = Server(url: instance, id: 'second-account');
            await db.upsertServer(other);
            await db.useServer(other);
          } else {
            await NetworkProxy.instance.initialize(
                saved: '{"enabled":true,"port":9999}', configureNative: false);
          }
        };
        respond = (request) async => http.Response('', 429,
            request: request, headers: {'retry-after': '1'});
        await expectLater(
            lookup.value(music), throwsA(isA<MusicCatalogException>()));
        expect(calls, hasLength(1));
      });
    }
  }

  test('Music retries a short rate limit in the same account and proxy',
      () async {
    final success = respond;
    respond = (request) async => calls.length == 1
        ? http.Response('', 429,
            request: request, headers: {'retry-after': '1'})
        : await success(request);
    final songs =
        await InvidiousMusicCatalogService(api: api).searchSongs('Song');
    expect(songs.single.videoId, videoId);
    expect(calls, hasLength(2));
    expect(calls.first, calls.last);
  });

  for (final change in ['none', 'account', 'proxy']) {
    test(
        'Music follows an instance redirect only in its original session ($change)',
        () async {
      final music = InvidiousMusicCatalogService(api: api);
      respond = (request) async {
        if (calls.length == 1) {
          if (change == 'account') {
            const other = Server(url: instance, id: 'second-account');
            await db.upsertServer(other);
            await db.useServer(other);
          } else if (change == 'proxy') {
            await NetworkProxy.instance.initialize(
                saved: '{"enabled":true,"port":9999}', configureNative: false);
          }
          return http.Response('', 302,
              request: request,
              headers: {'location': '/api/v1/redirected-search'});
        }
        return json(request, [song]);
      };
      if (change == 'none') {
        expect((await music.searchSongs('Song')).single.videoId, videoId);
        expect(calls.map((uri) => uri.path),
            ['/api/v1/search', '/api/v1/redirected-search']);
      } else {
        await expectLater(
            music.searchSongs('Song'), throwsA(isA<MusicCatalogException>()));
        expect(calls, hasLength(1));
      }
    });
  }

  for (final mode in ['manual backend', 'backend recovery', 'download']) {
    test('Music $mode drops a metadata retry after switching proxy', () async {
      final selected = (await db.getCurrentlySelectedServer()).copyWith(
          backendSelector: BackendSelector(
              'ROUTE',
              const [
                BackendOption('first', 'First'),
                BackendOption('second', 'Second')
              ],
              automaticFallback: true));
      await db.upsertServer(selected);
      final route = BackendPlayback.manual(selected, 'first');
      final source = await api.getMusicVideoForBackend(videoId, route);
      calls.clear();
      waitForRetry = (_) => NetworkProxy.instance.initialize(
          saved: '{"enabled":true,"port":9999}', configureNative: false);
      respond = (request) async => http.Response('', 429,
          request: request, headers: {'retry-after': '1'});
      final result = switch (mode) {
        'manual backend' => api.getMusicVideoForBackend(videoId, route),
        'backend recovery' => api.retryVideoBackend(
            source.copyWith(
                musicMetadata:
                    const MusicMetadata(title: 'Song', artist: 'Artist')),
            isCurrent: () => true),
        _ => api.getMusicVideo(videoId, serverOverride: selected),
      };
      await expectLater(result, throwsStateError);
      expect(calls, hasLength(1));
    });
  }

  test(
      'a NerdVPN metadata startup retry refuses a redirect off the chosen origin',
      () async {
    const account = Server(url: 'https://invidious.nerdvpn.de');
    await db.upsertServer(account);
    await db.useServer(account);
    respond = (request) async {
      if (calls.length == 1) {
        return json(
            request,
            {
              'error': 'This backend is still starting and not yet available. '
                  'Please wait for a short time or use another backend.',
            },
            status: 500);
      }
      return http.Response('', 302,
          request: request,
          headers: {'location': 'https://foreign.example/recording'});
    };
    await expectLater(InvidiousMusicCatalogService(api: api).getSong(videoId),
        throwsA(isA<http.ClientException>()));
    expect(calls.map((url) => url.origin), [account.url, account.url]);
  });
}
