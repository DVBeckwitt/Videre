enum VideoTranscriptLineType { heading, regular }

class VideoTranscriptLine {
  final VideoTranscriptLineType type;
  final int startMs;
  final int endMs;
  final String text;

  const VideoTranscriptLine({
    required this.type,
    required this.startMs,
    required this.endMs,
    required this.text,
  });
}

class VideoTranscript {
  final String label;
  final String? languageCode;
  final bool autoGenerated;
  final List<VideoTranscriptLine> lines;

  // Duration stores microseconds. Reject values that would overflow it when
  // captions are handed to the player.
  static const _maxTimestampMs = 0x7fffffffffffffff ~/ 1000;

  // Keep nonbreaking spaces inside captions so decoding &nbsp; does not change
  // where the subtitle renderer may wrap a line.
  static final _collapsibleWhitespace = RegExp(r'[^\S\u00a0]+');

  const VideoTranscript({
    required this.label,
    required this.languageCode,
    this.autoGenerated = false,
    required this.lines,
  });

  factory VideoTranscript.fromJson(Map<String, dynamic> json,
      {bool preserveRepeatedLines = false}) {
    final transcriptValue = json['transcript'];
    if (transcriptValue is! Map) {
      throw const FormatException('Missing transcript object');
    }

    final transcript = transcriptValue;
    final body = transcript['body'];
    if (body is! List) {
      throw const FormatException('Missing transcript body');
    }

    final lines = <VideoTranscriptLine>[];
    for (final entryValue in body) {
      if (entryValue is! Map) continue;
      final entry = entryValue;
      final startMs = _parseMilliseconds(entry['startMs']);
      final endMs = _parseMilliseconds(entry['endMs']);
      final lineValue = entry['line'];
      if (startMs == null || endMs == null || lineValue is! String) {
        continue;
      }

      final text = _cleanText(lineValue);
      if (text.isEmpty ||
          (!preserveRepeatedLines &&
              lines.isNotEmpty &&
              lines.last.text == text)) {
        continue;
      }

      lines.add(VideoTranscriptLine(
        type: entry['type'] == 'heading'
            ? VideoTranscriptLineType.heading
            : VideoTranscriptLineType.regular,
        startMs: startMs,
        endMs: endMs,
        text: text,
      ));
    }

    return VideoTranscript(
      label: transcript['label'] is String ? transcript['label'] as String : '',
      languageCode: transcript['languageCode'] is String
          ? transcript['languageCode'] as String
          : null,
      autoGenerated: transcript['autoGenerated'] == true,
      lines: lines,
    );
  }

  factory VideoTranscript.fromWebVtt(
    String webVtt, {
    required String label,
    String? languageCode,
    bool preserveRepeatedLines = false,
  }) {
    final source = webVtt
        .replaceAll('\r\n', '\n')
        .replaceAll('\r', '\n')
        .replaceFirst('\uFEFF', '');
    final sourceLines = source.split('\n');
    final transcriptLines = <VideoTranscriptLine>[];

    for (var index = 0; index < sourceLines.length; index++) {
      final timing = _parseTimingLine(sourceLines[index]);
      if (timing == null) continue;

      final cueText = <String>[];
      index++;
      while (
          index < sourceLines.length && sourceLines[index].trim().isNotEmpty) {
        if (_parseTimingLine(sourceLines[index]) != null) {
          index--;
          break;
        }
        cueText.add(sourceLines[index]);
        index++;
      }

      final text = _cleanText(cueText.join(' '));
      if (text.isEmpty ||
          (!preserveRepeatedLines &&
              transcriptLines.isNotEmpty &&
              transcriptLines.last.text == text)) {
        continue;
      }
      transcriptLines.add(VideoTranscriptLine(
        type: VideoTranscriptLineType.regular,
        startMs: timing.$1,
        endMs: timing.$2,
        text: text,
      ));
    }

    return VideoTranscript(
      label: label,
      languageCode: languageCode,
      lines: transcriptLines,
    );
  }

  /// Converts transcript content into captions without displaying section
  /// headings or treating the transcript's plain text as HTML.
  String toWebVtt() {
    final cues = lines
        .where((line) =>
            line.type == VideoTranscriptLineType.regular &&
            line.startMs >= 0 &&
            line.endMs > line.startMs &&
            line.endMs <= _maxTimestampMs &&
            line.text.trim().isNotEmpty)
        .toList();
    if (cues.isEmpty) {
      throw const FormatException('The transcript contains no playable cues.');
    }
    final output = StringBuffer('WEBVTT\n\n');
    for (var index = 0; index < cues.length; index++) {
      final cue = cues[index];
      var endMs = cue.endMs;
      if (autoGenerated &&
          endMs - cue.startMs == 10 &&
          index + 1 < cues.length &&
          cues[index + 1].startMs > endMs) {
        // Some Innertube transcripts give whole spoken lines a 10 ms end
        // marker. Infer their display interval from the next known cue start;
        // keep real durations and never invent an end after the final cue.
        endMs = cues[index + 1].startMs;
      }
      final text = cue.text
          .replaceAll(_collapsibleWhitespace, ' ')
          .trim()
          .replaceAll('&', '&amp;')
          .replaceAll('<', '&lt;')
          .replaceAll('>', '&gt;');
      output
        ..writeln('${_vttTimestamp(cue.startMs)} --> ${_vttTimestamp(endMs)}')
        ..writeln(text)
        ..writeln();
    }
    return output.toString();
  }

  static String _vttTimestamp(int milliseconds) {
    final hours = milliseconds ~/ 3600000;
    final minutes = milliseconds ~/ 60000 % 60;
    final seconds = milliseconds ~/ 1000 % 60;
    final fraction = milliseconds % 1000;
    return '${hours.toString().padLeft(2, '0')}:'
        '${minutes.toString().padLeft(2, '0')}:'
        '${seconds.toString().padLeft(2, '0')}.'
        '${fraction.toString().padLeft(3, '0')}';
  }

  String get plainText {
    final blocks = <String>[];
    final regularLines = <String>[];
    String? previousText;

    void flushRegularLines() {
      if (regularLines.isNotEmpty) {
        blocks.add(regularLines.join('\n'));
        regularLines.clear();
      }
    }

    for (final line in lines) {
      // Lines are already decoded plain text. Parsing markup again would
      // remove literal angle-bracket examples or decode escaped entities twice
      // when the transcript is copied.
      final text = line.text.replaceAll(_collapsibleWhitespace, ' ').trim();
      if (text.isEmpty || text == previousText) continue;
      previousText = text;

      if (line.type == VideoTranscriptLineType.heading) {
        flushRegularLines();
        blocks.add(text);
      } else {
        regularLines.add(text);
      }
    }
    flushRegularLines();

    return blocks.join('\n\n').trimRight();
  }

  static int? _parseMilliseconds(Object? value) {
    final number = value is num
        ? value
        : value is String
            ? num.tryParse(value)
            : null;
    if (number == null ||
        !number.isFinite ||
        number < 0 ||
        number > _maxTimestampMs) {
      return null;
    }
    return number.toInt();
  }

  static (int, int)? _parseTimingLine(String line) {
    final separator = line.indexOf('-->');
    if (separator < 0) return null;

    final start = _parseTimestamp(line.substring(0, separator).trim());
    final endAndSettings = line.substring(separator + 3).trim();
    final endToken = endAndSettings.split(RegExp(r'\s+')).first;
    final end = _parseTimestamp(endToken);
    if (start == null || end == null) return null;
    return (start, end);
  }

  static int? _parseTimestamp(String value) {
    final match = RegExp(
      r'^(?:(\d+):)?(\d{1,2}):(\d{2})(?:[\.,](\d{1,3}))?$',
    ).firstMatch(value);
    if (match == null) return null;

    final hours = int.tryParse(match.group(1) ?? '0');
    final minutes = int.tryParse(match.group(2)!);
    final seconds = int.tryParse(match.group(3)!);
    if (hours == null || minutes == null || seconds == null) return null;
    if (minutes > 59 && match.group(1) != null || seconds > 59) return null;
    if (hours > _maxTimestampMs ~/ 3600000) return null;

    final fraction = match.group(4) ?? '';
    final milliseconds = fraction.isEmpty
        ? 0
        : int.parse(fraction.padRight(3, '0').substring(0, 3));
    final timestamp =
        (((hours * 60) + minutes) * 60 + seconds) * 1000 + milliseconds;
    return timestamp <= _maxTimestampMs ? timestamp : null;
  }

  static String _cleanText(String value) {
    var text = value.replaceAll(RegExp(r'<[^>]*>'), '');
    // Decode once: replacing &amp; before &lt; would turn the literal &lt;
    // in an escaped example into a second decoded character.
    text = text.replaceAllMapped(
      RegExp(r'&(?:#(\d+)|#[xX]([0-9a-fA-F]+)|(amp|lt|gt|quot|nbsp|lrm|rlm));'),
      (match) {
        final named = match.group(3);
        if (named != null) {
          return const {
            'amp': '&',
            'lt': '<',
            'gt': '>',
            'quot': '"',
            'nbsp': '\u00a0',
            'lrm': '\u200e',
            'rlm': '\u200f',
          }[named]!;
        }
        final decimal = match.group(1);
        final codePoint = int.tryParse(decimal ?? match.group(2)!,
            radix: decimal == null ? 16 : 10);
        return codePoint == null
            ? match.group(0)!
            : _codePoint(codePoint, match);
      },
    );
    return text.replaceAll(_collapsibleWhitespace, ' ').trim();
  }

  static String _codePoint(int codePoint, Match match) {
    if (codePoint < 0 || codePoint > 0x10ffff) return match.group(0)!;
    return String.fromCharCode(codePoint);
  }
}
